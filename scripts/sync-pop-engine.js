#!/usr/bin/env node
// scripts/sync-pop-engine.js
//
// The guild lead, 2026-10-27: "Build in this sort of logic and put the flags checklist per character into
// motion" (the Flags mode of the PoP overlay in Mimic). "This sort of logic" is reading what a character holds
// into "what to do next": the next steps per progression line, the Seer's pending memories, which plane is done.
// All of it already exists, written once, in the website's TypeScript:
//
//     web/lib/popNextSteps.ts   NEXT_LINES, nextSteps()   the ordered next step per line, and what blocks it
//     web/lib/popRecital.ts     pendingNext(), heldClosure(), zoneViews()   pending memories, held closure, per-zone state
//     web/lib/popSteps.ts       POP_STEPS, STEP_IMPLIES, stepsHeld()
//     web/lib/popGuideSeer.ts   STEP_GUIDE        flag step -> guide step (the link the overlay jumps to)
//     web/lib/popSelfFlags.ts   selfFlagsFromTicks()    the owner's own ticks, as flags
//     web/lib/popWho.ts         flagsFromSightings()    /who proof, as flags
//
// The bot must not carry a hand-typed third copy of any of it (there is already a copy of the Seer's tables in
// utils/popFlagStages.js, kept honest by a parity test; this is the second reason not to add another). So, as
// for the Mimic quests (scripts/sync-pop-quests.js), the web files stay the SOURCE and the bot gets a GENERATED
// module: utils/popEngine.js, a CommonJS bundle of exactly the functions above.
//
//     npm run sync:pop-engine
//
// test/pop-engine-sync.test.js FAILS when the file is stale and runs the bundle against the TypeScript on the same
// fixtures; this script is how you fix the first failure. Never hand-edit the generated file.
//
// HOW: the .ts has extensionless relative imports (Node's own type stripping refuses them, and Node 20 has none),
// so it is bundled in memory with rolldown, which ships inside vite/vitest and is already installed (no new
// dependency). It only ever runs in this repo, never on the bot's host: the file it writes is plain CommonJS.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LIB = path.join(ROOT, 'web', 'lib');
const OUT = path.join(ROOT, 'utils', 'popEngine.js');

// What the bot reads from the web files. A name here that a web file stops exporting stops the bundle.
const ENTRY = [
  "export { NEXT_LINES, nextSteps, nextCard, topNext } from './popNextSteps';",
  "export { POP_STEPS, STEP_IMPLIES, stepsHeld } from './popSteps';",
  "export { STEP_GUIDE, guideStepFor, guideStepsProven } from './popGuideSeer';",
  "export { PENDING_MEMORIES, pendingHint, pendingNext, heldClosure, zoneViews } from './popRecital';",
  "export { POP_ZONES, POP_FLAGS, TIER_LABELS } from './popFlags';",
  "export { GUIDE_ITEMS } from './popGuide';",
  "export { SELF_TICK_KEYS, selfFlagsFromTicks } from './popSelfFlags';",
  "export { WHO_ZONE_NAMES, flagsFromSightings } from './popWho';",
].join('\n');

const HEADER = [
  '// utils/popEngine.js — the PoP flag engine, for the bot: what a character holds, read into what to do next.',
  '//',
  '// GENERATED by scripts/sync-pop-engine.js from web/lib/popNextSteps.ts, popSteps.ts, popGuideSeer.ts,',
  '// popRecital.ts, popFlags.ts, popGuide.ts, popSelfFlags.ts and popWho.ts — do not edit by hand. Change the web',
  '// files, then run `npm run sync:pop-engine`. test/pop-engine-sync.test.js fails when this file is stale, and runs it',
  '// against the TypeScript on the same fixtures. Used by utils/popStatus.js (the `pop` stream of /api/agent/poll).',
  '',
].join('\n');

async function bundleEngine() {
  const { rolldown } = await import('rolldown');
  const entry = path.join(LIB, '__pop-engine-entry.ts');
  const bundle = await rolldown({
    input: entry,
    cwd: ROOT,
    platform: 'node',
    logLevel: 'silent',
    plugins: [{
      name: 'pop-engine-entry',
      resolveId(id) { return id === entry ? id : null; },
      load(id) { return id === entry ? ENTRY : null; },
    }],
  });
  const { output } = await bundle.generate({ format: 'cjs', exports: 'named' });
  await bundle.close();
  return output[0].code;
}

// The exact text of utils/popEngine.js. Exported so the drift test uses the SAME transform.
async function buildSource() {
  const code = (await bundleEngine()).replace(/\r\n/g, '\n');
  // U+2028 / U+2029 inside a string are legal in modern JS; nothing to escape. Keep the text as rolldown wrote it.
  return HEADER + code.replace(/\s+$/, '') + '\n';
}

async function sync() {
  const src = await buildSource();
  const before = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (before === src) { console.log('✓ utils/popEngine.js already in sync with web/lib/pop*.ts'); return; }
  fs.writeFileSync(OUT, src);
  console.log('✓ utils/popEngine.js regenerated (' + src.length + ' chars)');
}

module.exports = { buildSource, OUT, ENTRY };
if (require.main === module) sync().catch((e) => { console.error(e); process.exit(1); });
