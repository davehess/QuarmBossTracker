comment on table public.raid_casts is 'One row per cast start relayed by Mimic. 60-day retention.';
comment on table public.raid_zone_changes is 'A character''s zone, on change. 60-day retention.';
comment on table public.raid_pet_owners is 'Pet and charm owner declarations. 60-day retention.';
comment on table public.raid_trigger_fires is 'Guild trigger fires accepted by the relay. 60-day retention.';
