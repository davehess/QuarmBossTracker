-- Raid history: six streams the bot used to hold only in memory, now saved (the guild lead, 2026-10-29, option C).
--
-- The bot already receives all of this while a raid is up and forgets it at every restart (a deploy, or a
-- crash) and at the next sample. utils/raidHistory.js decides, in memory, which observations are NEW and
-- appends them through ONE batched writer (every 5 s or 500 rows per table, never on the request path):
--
--   raid_mob_sightings  where a raider's target stood: a row when the character's target spawn changes, or the mob
--                       moved more than 10 units from where that character last saved it. x/y/z are in the Map's
--                       SERVER frame (the agent swaps the pipe's x and y before it uploads).
--   raid_mob_hp         a mob's health: a row when it stepped 5 points from the last saved value, or reached 0.
--                       Keyed by the mob, not by who looked; spawn_id is NULL only for a name no other mob shares.
--   raid_casts          who cast what on whom: one row per cast start (the same cast from two uploaders is one row).
--   raid_zone_changes   a character's zone, when it changes (and the first time the bot sees them: from_* NULL).
--   raid_pet_owners     each new "my leader is <owner>" pet / charm declaration.
--   raid_trigger_fires  a guild trigger fire the relay accepted (the relay already merged several observers into one).
--
-- RETENTION is 60 days in Supabase, swept nightly by the bot (RAID_HISTORY_RETENTION_DAYS). Every table has an
-- index whose LEADING column is its time column: encounter_threat_snapshots' sweep never worked because its time
-- predicate had no usable index. The Tower archive keeps these longer (scripts/lib/archive-merge.sql must list them).
--
-- Row ids are a plain identity primary key: the archive merge needs a primary key to move a table at all.
-- RLS is on with no policies: the bot writes with the service role, which bypasses it, and nothing else reads yet.
--
-- guild_id is set by the bot (default 'wolfpack'); no column holds free text a member typed.

create table if not exists public.raid_mob_sightings (
  id        bigint generated by default as identity primary key,
  guild_id  text        not null default 'wolfpack',
  seen_at   timestamptz not null default now(),
  character text        not null,
  zone      text        not null,               -- zone short name, as the agent sends it
  spawn_id  integer     not null,               -- an id in that zone's entity table
  mob_name  text        not null,
  x         real        not null,
  y         real        not null,
  z         real        not null default 0
);
create index if not exists raid_mob_sightings_seen_at_idx on public.raid_mob_sightings (seen_at);
alter table public.raid_mob_sightings enable row level security;

create table if not exists public.raid_mob_hp (
  id        bigint generated by default as identity primary key,
  guild_id  text        not null default 'wolfpack',
  at        timestamptz not null default now(),
  zone      text        not null default '',    -- where its observers stand (live-state zone name)
  spawn_id  integer,                            -- NULL = keyed by a unique name
  mob_name  text        not null,
  hp_pct    real        not null                -- 0-100; 0 is the death row
);
create index if not exists raid_mob_hp_at_idx on public.raid_mob_hp (at);
alter table public.raid_mob_hp enable row level security;

create table if not exists public.raid_casts (
  id          bigint generated by default as identity primary key,
  guild_id    text        not null default 'wolfpack',
  cast_at     timestamptz not null default now(),  -- when the cast began
  caster      text        not null,
  spell       text        not null,
  target      text        not null,
  target_id   integer,                             -- the caster's own target spawn id; NULL on a Zeal without it
  cast_secs   real,
  heal_amount integer                              -- the catalog's estimate for a heal; NULL otherwise
);
create index if not exists raid_casts_cast_at_idx on public.raid_casts (cast_at);
alter table public.raid_casts enable row level security;

create table if not exists public.raid_zone_changes (
  id             bigint generated by default as identity primary key,
  guild_id       text        not null default 'wolfpack',
  at             timestamptz not null default now(),
  character      text        not null,
  zone_id        integer,
  zone_name      text,
  from_zone_id   integer,                          -- NULL on the first time the bot saw this character
  from_zone_name text
);
create index if not exists raid_zone_changes_at_idx on public.raid_zone_changes (at);
alter table public.raid_zone_changes enable row level security;

create table if not exists public.raid_pet_owners (
  id           bigint generated by default as identity primary key,
  guild_id     text        not null default 'wolfpack',
  declared_at  timestamptz not null default now(),
  pet          text        not null,
  owner        text        not null,
  pet_spawn_id integer                              -- the owner's own Zeal read of the pet; NULL when not sent
);
create index if not exists raid_pet_owners_declared_at_idx on public.raid_pet_owners (declared_at);
alter table public.raid_pet_owners enable row level security;

create table if not exists public.raid_trigger_fires (
  id           bigint generated by default as identity primary key,
  guild_id     text        not null default 'wolfpack',
  fired_at     timestamptz not null default now(),
  trigger_name text        not null,
  trigger_key  text,                                -- name plus captures: what the relay deduped on
  captures     jsonb,                               -- at most 8 short values
  uploaded_by  text                                 -- the observing Mimic's Discord id
);
create index if not exists raid_trigger_fires_fired_at_idx on public.raid_trigger_fires (fired_at);
alter table public.raid_trigger_fires enable row level security;

