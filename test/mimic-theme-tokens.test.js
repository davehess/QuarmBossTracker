// test/mimic-theme-tokens.test.js — the overlays' shared theme file (apps/mimic/theme.css).
//
// docs/DESIGN-theming.md §2/§3/§7 step 2: every overlay window loads one stylesheet of colour slots as CSS variables,
// seeded with the values the overlays used before it existed, so a guild theme and a raider's own look can later be
// layers over it. This pins four things:
//   1. theme.css defines every slot, at today's values, and each rgb triplet equals its hex;
//   2. every window page loads it FIRST (before any <style> or other stylesheet), bar two named exceptions;
//   3. every var(--wp-…) a page or parts.js reads is a slot theme.css defines (a typo is a silent no-colour);
//   4. a RATCHET on raw hex colour literals per file: the counts may only go down. A page moving more colours onto
//      the slots lowers its number here in the same change; one that adds a hex goes red.
//
// Comments are stripped before any text assertion (the rule in CLAUDE.md: a comment can satisfy a matcher).
//
// Run: npx vitest run test/mimic-theme-tokens.test.js

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { readSource, stripJs, stripCss, ROOT } from './_source-slice.js';

const MIMIC = path.join(ROOT, 'apps', 'mimic');
const read = (f) => readSource(path.join(MIMIC, f));
const themeCss = stripCss(read('theme.css'));

// What the overlays used before theme.css existed (the platform palette, frontend-design SKILL.md). A change here is a
// re-theme of every overlay, so it is a deliberate edit of this table, not a side effect.
const SLOTS = {
  '--wp-bg': '#0d1117', '--wp-panel': '#161b22', '--wp-border': '#30363d', '--wp-text': '#c9d1d9', '--wp-dim': '#6e7681',
  '--wp-accent': '#1f6feb', '--wp-blue': '#58a6ff', '--wp-purple': '#a371f7',
  '--wp-green': '#56d364', '--wp-red': '#f85149', '--wp-gold': '#d29922', '--wp-orange': '#ffa657',
};
const TRIPLETS = { '--wp-bg-rgb': '--wp-bg', '--wp-panel-rgb': '--wp-panel' };
const OTHER_SLOTS = ['--wp-radius', '--wp-font-mono', '--wp-font-ui'];

const slotValue = (name) => {
  const m = themeCss.match(new RegExp('(?:^|[;{\\s])' + name.replace(/-/g, '\\-') + '\\s*:\\s*([^;]+);'));
  return m ? m[1].trim() : null;
};

// Every .html in apps/mimic is a BrowserWindow page. Two do not load theme.css, each for a reason that is checked:
//  - command.html is served by the agent too (its COMMAND_HTML embed at /overlay/command, no theme.css beside it), and
//    the embed is byte-exact, so it keeps its own colours until the embed itself is regenerated by that step;
//  - storage.html is an empty hidden page that only borrows the shared localStorage.
const EXEMPT = { 'command.html': 'agent-served embed', 'storage.html': 'empty hidden page' };
const PAGES = fs.readdirSync(MIMIC).filter((f) => f.endsWith('.html')).sort();
const THEMED = PAGES.filter((f) => !EXEMPT[f]);

// Raw hex colour literals per file, comments stripped. Shrink-only: lower a number when a file loses hex, never raise.
// What is left is not a theme slot's value (#8b949e, #e6edf3, #000, #fff, class and map colours, one-off tints) or must
// stay a literal (canvas drawing, a value validated as hex, 8-digit alpha hex).
const HEX_BASELINE = {
  'buffqueue.html': 68, 'canvas.html': 25, 'charm.html': 56, 'chat.html': 66, 'chchain.html': 164, 'command.html': 165,
  'dock.html': 28, 'extarget.html': 81, 'loading.html': 78, 'map.html': 243, 'me.html': 46, 'melody.html': 48,
  'mobinfo.html': 140, 'overlay.html': 47, 'parts.js': 35, 'pets.html': 34, 'popraid.html': 88, 'resources.html': 18,
  'settings.html': 183, 'setup-share.html': 15, 'storage.html': 0, 'tank.html': 126, 'threatmeter.html': 27,
  'triggers.html': 71, 'ui-studio.html': 197, 'welcome.html': 23, 'who.html': 59, 'zealhealth.html': 33,
};
const HEX = /(?<![\w&])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![\w-])/g;
// Markup is left as it is; each <style> goes through the CSS stripper and each <script> through the JS one.
const stripped = (file, src) => file.endsWith('.html')
  ? src.replace(/<!--[\s\S]*?-->/g, '')
    .replace(/(<style\b[^>]*>)([\s\S]*?)(<\/style>)/g, (m, a, b, c) => a + stripCss(b) + c)
    .replace(/(<script\b[^>]*>)([\s\S]*?)(<\/script>)/g, (m, a, b, c) => a + stripJs(b) + c)
  : stripJs(src);
const hexCount = (file) => (stripped(file, read(file)).match(HEX) || []).length;

describe('theme.css', () => {
  it('defines every colour slot at the value the overlays used before it existed', () => {
    for (const [name, hex] of Object.entries(SLOTS)) expect(slotValue(name), name).toBe(hex);
  });

  it('defines the radius and the two font stacks', () => {
    for (const name of OTHER_SLOTS) expect(slotValue(name), name).toBeTruthy();
  });

  it('keeps each rgb triplet equal to the hex of its slot', () => {
    for (const [name, slot] of Object.entries(TRIPLETS)) {
      const h = SLOTS[slot];
      const want = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)).join(', ');
      expect(slotValue(name), name).toBe(want);
    }
  });

  it('sets the slots on :root and nothing else (it is a variable file, not a stylesheet)', () => {
    const rules = themeCss.replace(/:root\s*\{[^}]*\}/g, '').trim();
    expect(rules).toBe('');
  });
});

describe('every window page loads the theme first', () => {
  it('knows why each page that does not', () => {
    expect(Object.keys(EXEMPT).sort()).toEqual(['command.html', 'storage.html']);
    expect(stripped('command.html', read('command.html'))).not.toMatch(/theme\.css|var\(--wp-/);
    expect(read('storage.html')).not.toMatch(/<style|<link/);
  });

  it('is a real BrowserWindow page: main.js loads each html file in the folder by name', () => {
    const main = stripJs(readSource(path.join(MIMIC, 'main.js')));
    for (const f of PAGES) expect(main.includes("'" + f + "'"), f).toBe(true);
  });

  for (const f of THEMED) {
    it(f + ' links theme.css before any <style> or other stylesheet', () => {
      const head = read(f).replace(/<!--[\s\S]*?-->/g, '');
      const TAG = '<link rel="stylesheet" href="theme.css">';
      const link = head.indexOf(TAG);
      expect(link, 'theme.css link').toBeGreaterThan(-1);
      const style = head.indexOf('<style');
      if (style > -1) expect(link).toBeLessThan(style);
      const otherLink = head.search(/<link[^>]*rel="stylesheet"[^>]*href="(?!theme\.css)/);
      if (otherLink > -1) expect(link).toBeLessThan(otherLink);
      expect(head.indexOf('theme.css', link + TAG.length), 'once').toBe(-1);
    });
  }
});

describe('the slots a page reads exist', () => {
  const defined = new Set([...Object.keys(SLOTS), ...Object.keys(TRIPLETS), ...OTHER_SLOTS]);
  for (const f of [...THEMED, 'parts.js']) {
    it(f + ' reads only slots theme.css defines', () => {
      const used = new Set([...stripped(f, read(f)).matchAll(/var\((--wp-[a-z-]+)/g)].map((m) => m[1]));
      for (const name of used) expect(defined.has(name), name).toBe(true);
    });
  }

  it('parts.js reads its colour map from the theme and falls back to the same hex', () => {
    const src = stripJs(read('parts.js'));
    for (const [name, hex] of Object.entries(SLOTS)) {
      const slot = name.slice('--wp-'.length);
      if (!['text', 'dim', 'blue', 'gold', 'green', 'red', 'orange', 'purple'].includes(slot)) continue;
      expect(src).toContain("themed('" + slot + "', '" + hex + "')");
    }
  });
});

describe('raw hex colour literals only go down', () => {
  it('covers every window page and parts.js', () => {
    expect(Object.keys(HEX_BASELINE).sort()).toEqual([...PAGES, 'parts.js'].sort());
  });

  it('counts', () => {
    const rows = [];
    for (const f of Object.keys(HEX_BASELINE)) rows.push([f, hexCount(f), HEX_BASELINE[f]]);
    // eslint-disable-next-line no-console
    console.log('raw hex literals (now / baseline):\n' + rows.map(([f, n, b]) => '  ' + f.padEnd(18) + String(n).padStart(4) + ' / ' + b).join('\n'));
    for (const [f, n, b] of rows) expect(n, f + ' gained hex colour literals').toBeLessThanOrEqual(b);
  });

  it('no token value is written as a literal in a CSS rule of a themed page', () => {
    // The slots' own hex belongs in theme.css. A <style> rule that spells one is a colour that will not follow a theme.
    const tokenHex = new RegExp('(?<![\\w&])(?:' + Object.values(SLOTS).join('|') + ')(?![\\w-])', 'gi');
    for (const f of THEMED) {
      const css = [...stripped(f, read(f)).matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n');
      const left = css.match(tokenHex) || [];
      expect(left, f).toEqual([]);
    }
  });
});
