// test/pop-engine-sync.test.js — utils/popEngine.js is GENERATED from the website's PoP flag engine
// (web/lib/popNextSteps.ts, popSteps.ts, popGuideSeer.ts, popRecital.ts, popFlags.ts, popGuide.ts, popSelfFlags.ts,
// popWho.ts) by scripts/sync-pop-engine.js. The bot may not carry a hand-typed third copy of the progression rules, so
// this is the gate that says it does not: the file is exactly what the generator writes now (edit the web files, forget
// the sync, and a red here says `npm run sync:pop-engine`), AND the bundle answers like the TypeScript on the same inputs
// (a generator that bundled the wrong thing, or a bundler upgrade that changed behaviour, would fail the second part with
// a clean file).
//
// The guild lead, 2026-10-27: "A then B" for the per-character PoP flags checklist in Mimic; the logic is "reading
// #popflags / Seer lines into what to do next", which the website already does.
//
// Run: npx vitest run test/pop-engine-sync.test.js

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { ROOT } from './_source-slice.js';
import * as nextTs from '../web/lib/popNextSteps.ts';
import * as stepsTs from '../web/lib/popSteps.ts';
import * as seerTs from '../web/lib/popGuideSeer.ts';
import * as recitalTs from '../web/lib/popRecital.ts';
import * as flagsTs from '../web/lib/popFlags.ts';
import * as selfTs from '../web/lib/popSelfFlags.ts';
import * as whoTs from '../web/lib/popWho.ts';

const require = createRequire(import.meta.url);
const sync = require(path.join(ROOT, 'scripts', 'sync-pop-engine.js'));
const E = require(path.join(ROOT, 'utils', 'popEngine.js'));
// (CRLF-tolerant: a Windows checkout with autocrlf must not read as drift.)
const generated = fs.readFileSync(sync.OUT, 'utf8').replace(/\r\n/g, '\n');

// A small seeded generator so the "random" sets are the same every run.
function rng(seed) { let s = seed >>> 0; return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 2 ** 32); }
const ALL_KEYS = [...new Set([
  ...Object.values(stepsTs.POP_STEPS).flat().map(s => s.key),
  ...Object.keys(flagsTs.POP_FLAGS),
  ...recitalTs.PENDING_MEMORIES.map(m => m.key),
  'hohtrials_111',
])];
const SETS = (() => {
  const out = [[], ALL_KEYS.slice()];
  const r = rng(20261027);
  for (let n = 0; n < 40; n++) out.push(ALL_KEYS.filter(() => r() < 0.1 + 0.02 * n));
  // The partway character the Flags mode is drawn for.
  out.push(['mavuin_3', 'zeks_2', 'thelin_4', 'karana_4', 'aerindar_2', 'mmarr_1', 'zeks_3', 'zeks_4', 'cl_grummus', 'cl_rallos']);
  // Maelin's readings (Grand_Librarian_Maelin.lua): the Zek notes need the cipher, the second reading needs zeks 7.
  out.push(['behemoth_dead', 'vallon_dead', 'tallon_dead']);
  out.push(['behemoth_dead', 'vallon_dead', 'tallon_dead', 'cipher_1']);
  out.push(['cipher_1', 'zebuxoruk_1', 'zeks_6', 'askr_quest', 'agnarr_dead', 'marr_dead']);
  out.push(['cipher_1', 'zebuxoruk_1', 'zeks_7', 'askr_quest', 'agnarr_dead', 'marr_dead']);
  return out;
})();

describe('utils/popEngine.js is the generated copy of the web flag engine', () => {
  it('is exactly what the generator writes now (a red here means: npm run sync:pop-engine)', async () => {
    const want = await sync.buildSource();
    // Not expect(a).toBe(b): a 150 KB string diff buries the one line that matters.
    expect(generated === want, 'utils/popEngine.js is stale: run npm run sync:pop-engine').toBe(true);
  });

  it('carries its do-not-edit banner and exports what utils/popStatus.js reads', () => {
    expect(generated).toMatch(/GENERATED by scripts\/sync-pop-engine\.js[\s\S]{0,300}do not edit/);
    for (const name of ['NEXT_LINES', 'nextSteps', 'nextCard', 'topNext', 'POP_STEPS', 'STEP_IMPLIES', 'stepsHeld', 'STEP_GUIDE',
      'guideStepFor', 'guideStepsProven', 'PENDING_MEMORIES', 'pendingHint', 'pendingNext', 'heldClosure', 'zoneViews',
      'POP_ZONES', 'POP_FLAGS', 'GUIDE_ITEMS', 'SELF_TICK_KEYS', 'selfFlagsFromTicks', 'WHO_ZONE_NAMES', 'flagsFromSightings']) {
      expect(E[name], name).toBeDefined();
    }
  });

  it('holds no machine path (the repo is public; the bundle must be the same wherever it is built)', () => {
    expect(generated).not.toMatch(/\/home\/|[A-Z]:\\|node_modules/);
  });
});

describe('the bundle answers exactly like the TypeScript, on the same inputs', () => {
  const j = (v) => JSON.stringify(v, (_k, x) => (x instanceof Set ? [...x].sort() : (x instanceof Map ? [...x.entries()] : x)));

  it('has the same tables', () => {
    expect(j(E.NEXT_LINES)).toBe(j(nextTs.NEXT_LINES));
    expect(j(E.POP_STEPS)).toBe(j(stepsTs.POP_STEPS));
    expect(j(E.STEP_IMPLIES)).toBe(j(stepsTs.STEP_IMPLIES));
    expect(j(E.STEP_GUIDE)).toBe(j(seerTs.STEP_GUIDE));
    expect(j(E.PENDING_MEMORIES)).toBe(j(recitalTs.PENDING_MEMORIES));
    expect(j(E.POP_ZONES)).toBe(j(flagsTs.POP_ZONES));
    expect(j(E.WHO_ZONE_NAMES)).toBe(j(whoTs.WHO_ZONE_NAMES));
    expect(j(E.SELF_TICK_KEYS)).toBe(j(selfTs.SELF_TICK_KEYS));
  });

  it('nextSteps / heldClosure / stepsHeld / pendingNext / zoneViews agree on ' + SETS.length + ' sets of held keys', () => {
    for (const keys of SETS) {
      const at = keys.length + ' keys: ' + keys.slice(0, 4).join(',');
      expect(j(E.stepsHeld(keys)), at).toBe(j(stepsTs.stepsHeld(keys)));
      const heldTs = recitalTs.heldClosure(keys);
      const held = E.heldClosure(keys);
      expect(j(held), at).toBe(j(heldTs));
      expect(j(E.nextSteps({ done: [], flags: held })), at).toBe(j(nextTs.nextSteps({ done: [], flags: heldTs })));
      expect(j(E.pendingNext(keys, held)), at).toBe(j(recitalTs.pendingNext(keys, heldTs)));
      expect(j(E.zoneViews(held)), at).toBe(j(recitalTs.zoneViews(heldTs)));
      expect(j(E.topNext(E.nextSteps({ done: [], flags: held }), 5)), at).toBe(j(nextTs.topNext(nextTs.nextSteps({ done: [], flags: heldTs }), 5)));
    }
  });

  it('selfFlagsFromTicks and flagsFromSightings agree', () => {
    const ticks = [
      { character_name: 'Brackwyn', item_key: 'flag_grummus' },
      { character_name: 'Brackwyn', item_key: 'flag:tthule_dead' },
      { character_name: 'Corvale', item_key: 'not_a_key' },
    ];
    expect(j(E.selfFlagsFromTicks(ticks))).toBe(j(selfTs.selfFlagsFromTicks(ticks)));
    const sights = whoTs.WHO_ZONE_NAMES.slice(0, 6).map((zone, n) => ({ zone, first_seen: '2026-10-2' + n + 'T20:00:00Z', last_seen: '2026-10-2' + n + 'T21:00:00Z' }));
    expect(j(E.flagsFromSightings(sights))).toBe(j(whoTs.flagsFromSightings(sights)));
    expect(E.flagsFromSightings(sights).size).toBeGreaterThan(0);
  });
});
